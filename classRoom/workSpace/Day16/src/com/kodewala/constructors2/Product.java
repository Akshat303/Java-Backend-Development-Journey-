package com.kodewala.constructors2;

public class Product {
	String name;
	int price;
	String sku;
	String productType;
	
	public Product(String _name, int _price, String _sku, String _productType) {

		this.name = _name;
		this.price = _price;
		this.sku = _sku;
		this.productType = _productType;
	}
	

	

}
